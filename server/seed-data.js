function fornitore(nazione) {
  return {
    _id: nazione.codice,
    schemaVersion: versione(),
    codice: nazione.codice,
    nome: nazione.nome,
    bandiera: nazione.bandiera,
    profilo: {
      nomeUfficiale: nazione.nomeUfficiale,
      capitale: nazione.capitale,
      sintesi: nazione.sintesi,
      ufficioDati: nazione.ufficio,
      email: nazione.email,
    },
    sovranita: {
      dichiarazione: nazione.dichiarazione,
      giurisdizione: nazione.giurisdizione,
    },
  };
}

function politica(livello, condizioni, finalita) {
  if (livello === 'aperto') {
    return {
      livello,
      ilProprietarioDecide: false,
      finalitaAmmesse: finalita || ['pianificazione', 'quadro operativo comune'],
      ridistribuzione: 'Consentita nel perimetro della missione, citando la nazione che pubblica.',
      conservazione: 'Secondo le regole di chi usa il dato aperto.',
      condizioni,
    };
  }
  return {
    livello,
    ilProprietarioDecide: true,
    finalitaAmmesse: finalita,
    ridistribuzione: 'Vietata verso terzi senza una nuova decisione del proprietario.',
    conservazione: 'Solo per la durata della concessione. Alla revoca l\'uso si interrompe.',
    condizioni,
  };
}

function campi(...voci) {
  return voci.map(([nome, descrizione, unita]) => {
    const campo = { nome, descrizione };
    if (unita) campo.unita = unita;
    return campo;
  });
}

